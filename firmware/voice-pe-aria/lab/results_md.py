"""Write results/RESULTS_TABLES.md - every table of the final report, generated from the
machine-readable results (no hand-copied numbers):
  phase2_results.json, recommendation.json, naming_risk.json, model_status.json,
  pronunciation_identity.json, device_test_build.json (if built), discovery*.json
"""
import json

from lab_common import LAB, REPORT_CUTOFF, load_all_candidates

R = LAB / "results"


def load(name):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def pct(x):
    return "—" if x is None else f"{100 * x:.1f}%"


def main():
    p2 = load("phase2_results.json")["models"]
    rec = load("recommendation.json")
    risk = load("naming_risk.json") or {}
    status = load("model_status.json") or {}
    pron = load("pronunciation_identity.json") or {}
    build = load("device_test_build.json")
    cands = load_all_candidates()
    o = ["# Wake Word Lab — result tables (generated by `results_md.py`)", "",
         "**All models: RESEARCH ONLY — NOT COMMERCIALLY RELEASABLE.** Synthetic evidence only; the "
         "physical Voice PE test is the final decision gate. No permanent wake word is declared.", "",
         "**How to read the measures** (all are simulated lab estimates, not real-room rates):", "",
         "- *True wake / catch rate (TPR)*: share of held-out synthetic recordings of the candidate phrase "
         "(144 per candidate: 24 held-out voices × careful/intended/casual forms, each under every listed "
         "condition) that woke the model.",
         "- *Wrong-word wakes (confusion FA rate)*: share of synthetic recordings of other words and phrases "
         "(sound-alikes such as area / Maria / Krista, launcher-only and senior-living vocabulary, everyday "
         "sentences, and the supplemental confusion list) that wrongly woke the model. Wakes on other "
         "candidates' phrases are reported separately as cross-triggers.",
         "- *Simulated false wakes per hour (ambient FA/h)*: wakes counted while the model listened to about "
         "5.6 h of ambient audio (TV-dialogue proxy from LibriSpeech, held-out music, DEMAND room background, "
         "procedural HVAC, silence), 2 s refractory. One event ≈ 0.18/h, so values below ~0.4/h are 0–2 "
         "events. This is a lab estimate, not an established hourly rate in a real room.",
         "- *Matched cutoff*: the lowest threshold at which that simulated ambient rate is ≤ 0.5/h; every "
         "model is compared at its own matched cutoff.",
         "- Every model saw identical evaluation clips, identical per-clip noise and augmentation seeds, and "
         "identical ambient streams (see METHODOLOGY.md, evaluation determinism).", ""]
    o += ["## 1. Status of all candidates", "",
          "| # | Candidate | Group | Form | Status | Cross-check | Train min | Model SHA-256 | Config SHA-256 |",
          "|---|---|---|---|---|---|---|---|---|"]
    for i, c in enumerate(cands, 1):
        s = status.get(c["slug"], {})
        o.append(f"| {i} | {c['id']} | {c.get('group', 'original 15')} | {s.get('form', '')} | "
                 f"{s.get('status', 'MISSING')} | {'yes' if s.get('cross_check_done') else 'no'} | "
                 f"{s.get('train_duration_min', '')} | `{(s.get('sha256') or '')[:16]}` | "
                 f"`{(s.get('training_parameters_sha256') or '')[:16]}` |")
    o += ["", "Full hashes: `results/provenance.json` and `results/model_status.json`.", ""]
    o += ["## 2. Ranking (weighted score; raw factor values shown)", "",
          f"Weights: {rec['weights']}. Memorability and natural identity are human-factors judgements. "
          "Licensing is a hard gate (all research-only) and is not scored.", "",
          "| Rank | Candidate | Weighted | True wake | False wake | Older resident | Memorability | Natural identity | "
          "Matched cutoff | TPR all | Confusion FA rate (incl. extra) | Ambient FA/h |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rec["ranked"], 1):
        s = r["scores"]
        o.append(f"| {i} | {r['id']} | {r['balanced']} | {s['true_wake']} | {s['false_wake']} | {s['older_resident']} | "
                 f"{s['memorability']} | {s['natural_identity']} | {r['matched_cutoff']} | {pct(r['matched_tpr'])} | "
                 f"{pct(r['confusion_rate'])} | {r['ambient_faph']} |")
    o += ["", "Selection rules: " + "; ".join(rec.get("selection_rules", [])) + ".", "",
          f"**Five finalists:** {', '.join(rec['five_finalists'])}", "",
          f"**Three physical Voice PE finalists:** {', '.join(rec['physical_test_three'])}"
          + (f" — {rec['natural_name_rule']}" if rec.get("natural_name_rule") else ""), ""]
    o += ["## 3. Side-by-side catch rates at each model's matched cutoff (simulated ambient ≤ 0.5 false wakes/h)", "",
          "| Candidate | Cutoff | Quiet room 2 m | Clean near | TV on | Other talker | Low volume | 1 m | 4 m | Bed/away | "
          "HVAC/music/noise | Missed (all) |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in cands:
        m = p2.get(c["slug"])
        if not m:
            continue
        g = lambda k: pct(m.get(f"matched_tpr_{k}"))
        o.append(f"| {c['id']} | {m['matched_cutoff']} | {g('quiet_room_2m')} | {g('clean_near')} | {g('tv_on')} | "
                 f"{g('other_talker')} | {g('low_volume')} | {g('distance_1m')} | {g('distance_4m')} | "
                 f"{g('bed_facing_away')} | {g('hvac_music_noise')} | {pct(m['matched_missed_wake_rate_all_conditions'])} |")
    o += ["", "## 4. Simulated older-resident conditions (matched cutoff, true-wake rate)", "",
          "| Candidate | Older voice | Raspy | Dentures | Weak first sound | Shortened ending | Run-together | Low volume |",
          "|---|---|---|---|---|---|---|---|"]
    for c in cands:
        m = p2.get(c["slug"])
        if m:
            g = lambda k: pct(m.get(f"matched_tpr_{k}"))
            o.append(f"| {c['id']} | {g('older_sim')} | {g('raspy_sim')} | {g('dentures_sim')} | {g('weak_onset')} | "
                     f"{g('short_final')} | {g('run_together')} | {g('low_volume')} |")
    o += ["", "## 5. Simulated false wakes per hour (lab estimate, matched cutoff)", "",
          "| Candidate | TV dialogue proxy | Music | Room background | HVAC | Silence | Combined ambient | "
          "Same at fixed 0.90 |", "|---|---|---|---|---|---|---|---|"]
    for c in cands:
        m = p2.get(c["slug"])
        if m:
            o.append(f"| {c['id']} | {m['matched_false_per_hour_tv_dialogue']} | {m['matched_false_per_hour_music']} | "
                     f"{m['matched_false_per_hour_background']} | {m['matched_false_per_hour_hvac']} | "
                     f"{m['matched_false_per_hour_silence']} | {m['matched_ambient_false_per_hour']} | "
                     f"{m['fixed_ambient_false_per_hour']} |")
    o += ["", f"Fixed operating point = {REPORT_CUTOFF} for every model. Threshold trade-offs for every cutoff: "
          "`results/phase2_roc.csv`. Confusion matrix by phrase: `results/phase2_confusion.csv`. "
          "Cross-trigger matrix: `results/phase2_cross_trigger.csv`.", ""]
    o += ["## 6. Bare word vs launcher (matched cutoff)", "",
          "| Base | Variant | TPR all | TV on | Low volume | Confusion FA rate | Ambient FA/h |",
          "|---|---|---|---|---|---|---|"]
    for base, vs in rec["bare_vs_launcher"].items():
        for v in vs:
            o.append(f"| {base} | {v['id']} | {pct(v['matched_tpr'])} | {pct(v['tpr_tv_on'])} | "
                     f"{pct(v['tpr_low_volume'])} | {pct(v['confusion_rate'])} | {v['ambient_faph']} |")
    o += ["", "## 7. Pronunciation variation", "", "Per-form true-wake rate (clean, matched cutoff):", "",
          "| Candidate | Careful | Intended | Casual | AIR-ee-uh / area-like accepted |", "|---|---|---|---|---|"]
    for c in cands:
        m = p2.get(c["slug"])
        if m:
            area = next((v for k, v in m.items() if k.startswith("matched_accept_air")), None)
            o.append(f"| {c['id']} | {pct(m.get('matched_tpr_form_careful'))} | {pct(m.get('matched_tpr_form_intended'))} | "
                     f"{pct(m.get('matched_tpr_form_casual'))} | {pct(area)} |")
    if pron:
        o += ["", "Same-spelling pronunciation identity test (`pronunciation_identity.py`):", "",
              "| Word | A | B | Between/within | Wilcoxon p | Conclusion |", "|---|---|---|---|---|---|"]
        for w, v in pron.items():
            o.append(f"| {w} | {v['ipa_a']} | {v['ipa_b']} | {v['between_over_within']} | "
                     f"{v['wilcoxon_p_between_gt_within']:.2g} | {v['conclusion']} |")
    o += ["", "## 8. Naming / brand risk (separate, unscored; no legal conclusion)", "",
          "| Candidate | Common word | Personal name | Resident/staff collision | Near-sound names (Census %) | "
          "Product/place association | Pronunciation ambiguity | Spelling ambiguity | Legal review |",
          "|---|---|---|---|---|---|---|---|---|"]
    for c in cands:
        k = risk.get(c["slug"])
        if not k:
            continue
        near = ", ".join(f"{n} {v}" if v else n for n, v in (k.get("near_sound_common_names") or {}).items())
        o.append(f"| {c['id']} | {'yes' if k['known_common_word']['flag'] else 'no'} | "
                 f"{'yes' if k['common_personal_name']['flag'] else 'no'} | "
                 f"{'yes: ' + ', '.join(k['resident_staff_collision']['evidence']) if k['resident_staff_collision']['flag'] else 'no'} | "
                 f"{near or '—'} | {k['product_association']} | "
                 f"{'yes' if k['pronunciation_ambiguity']['flag'] else 'no'} | "
                 f"{', '.join(k['spelling_ambiguity']['other_spellings_same_or_near_sound']) or 'no'} | yes |")
    o += ["", "## 9. Model size, memory, latency", "",
          "| Candidate | Model bytes | Arena bytes (RAM) | Median detection latency after speech end | Host ms per inference |",
          "|---|---|---|---|---|"]
    for c in cands:
        m = p2.get(c["slug"])
        if m:
            o.append(f"| {c['id']} | {m['tflite_bytes']} | {m['arena_bytes']} | {m['detection_latency_ms_median']} ms | "
                     f"{round(m['host_inference_ms_per_step'], 3)} |")
    if build:
        o += ["", "## 10. Physical-test research firmware", "", f"Compile exit: {build['compile_exit']}; "
              f"{build.get('ram_line')}; {build.get('flash_line')}", ""]
        for b in ("firmware.factory.bin", "firmware.ota.bin"):
            if b in build:
                o.append(f"- `{b}`: {build[b]['bytes']} B, SHA-256 `{build[b]['sha256']}`")
        o += ["", "Finalist models (kept out of git, research-only):", ""]
        for f in build["finalists"]:
            o.append(f"- {f['id']}: cutoff {f['cutoff']}, arena {f['arena']}, model SHA-256 `{f['tflite_sha256']}`")
    (R / "RESULTS_TABLES.md").write_text("\n".join(o) + "\n")
    print("written", len(o), "lines")


if __name__ == "__main__":
    main()
